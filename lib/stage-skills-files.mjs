/**
 * The stage skills on disk — CMP-0033, TSK-0046, against ACC-0066.
 *
 * `lib/stage-skills.mjs` decides what the packaged skills should say. This module compares that
 * answer with what `pi-package/skills/` holds, and in write mode makes the directory agree.
 *
 * ⚠️ **ONE GENERATOR, TWO USES.** The check and the write both start from the same plan, built from
 * the same call to `generateStageSkills`. A check that compared against output a different code path
 * produced could pass while the write produced something else, and that is the only way a check of
 * this kind lies.
 *
 * ⚠️ **THE GENERATOR OWNS `kiln-stage-*` AND NOTHING ELSE UNDER `pi-package/skills/`.** A skill whose
 * name `isStageSkillName` rejects - `kiln-planning`, a consumer's own - is never opened, never
 * reported, never written and never removed.
 *
 * ⚠️ **A GENERATED NAME IS NOT PROOF OF GENERATED CONTENT.** An orphaned `kiln-stage-*` directory is
 * removed only when it holds exactly one `SKILL.md` carrying the generator's header. Anything else in
 * it is somebody's work, so write mode refuses rather than deleting a directory it cannot account for.
 *
 * ⚠️ **NOTHING IS WRITTEN UNTIL EVERYTHING HAS BEEN CHECKED.** Write mode refuses on any refusal found
 * anywhere in the plan, before its first write, so a refused run leaves the directory exactly as it was.
 *
 * ⚠️ **EVERY DIAGNOSTIC NAMES A SKILL OR A RELATIVE PATH.** A message carrying this machine's paths is
 * a message that cannot be pasted into an issue, and it is the kind of text that ends up in CI logs.
 */

import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmdirSync, unlinkSync } from "node:fs";
import { join } from "node:path";

import { atomicWrite } from "./atomic-write.mjs";
import { canonicalPath, isAtOrInside } from "./content-root.mjs";
import { byCodeUnit } from "./project-scaffold.mjs";
import { SKILLS_DIR, SKILL_FILE, StageSkillError, generateStageSkills, isStageSkillName } from "./stage-skills.mjs";
import { loadStageDefinitions } from "./stages.mjs";

export const PACKAGE_DIR = "pi-package";

/** The first line of every generated body. Ownership of an orphan is decided by it, and by nothing else. */
export const GENERATED_HEADER = "<!-- Generated by lib/stage-skills.mjs from stages/";

export const DRIFT = Object.freeze({ STALE: "stale", MISSING: "missing", ORPHANED: "orphaned" });

export const SYNC_REFUSAL = Object.freeze({
  NO_DEFINITIONS: "stage-definitions-missing",
  MALFORMED: "stage-definitions-malformed",
  NO_SKILLS_DIR: "skills-directory-missing",
  PATH_ESCAPE: "path-escapes-skills-directory",
  LINKED_ENTRY: "linked-entry",
  UNOWNED_CONTENT: "unowned-content",
  NOT_A_SKILL: "not-a-generated-skill",
  IO: "io-error",
  UNVERIFIED: "write-not-verified",
});

const DRIFT_ORDER = [DRIFT.STALE, DRIFT.MISSING, DRIFT.ORPHANED];

/** The relative location a diagnostic may name: always from the tool root, always with `/`. */
const shown = (...segments) => [PACKAGE_DIR, SKILLS_DIR, ...segments].join("/");

const refusal = (code, message, skill = null) => ({ code, message, skill });

/** An I/O failure reduced to its code and the relative place it happened, never the absolute path. */
const ioRefusal = (error, where, skill = null) =>
  refusal(SYNC_REFUSAL.IO, `${where} could not be read or written (${error?.code ?? error?.name ?? "unknown error"}).`, skill);

const byNameThenKind = (a, b) =>
  byCodeUnit(a.skill ?? "", b.skill ?? "") || DRIFT_ORDER.indexOf(a.kind) - DRIFT_ORDER.indexOf(b.kind) || byCodeUnit(a.code ?? "", b.code ?? "");

/**
 * What the definitions call for, compared with what the skills directory holds. Reads only.
 *
 * @param {string} toolRoot
 * @returns {{
 *   skills: ReadonlyArray<{stageId: string, name: string, path: string, content: string}>,
 *   drift: Array<{kind: string, skill: string, path: string, owned?: boolean, unowned?: string[]}>,
 *   refusals: Array<{code: string, message: string, skill: string|null}>,
 * }}
 */
export function planStageSkills(toolRoot) {
  const root = canonicalPath(toolRoot);
  const packageRoot = join(root, PACKAGE_DIR);
  const skillsRoot = join(packageRoot, SKILLS_DIR);
  const drift = [];
  const refusals = [];
  const done = (skills = []) => ({ skills, drift: drift.sort(byNameThenKind), refusals: refusals.sort(byNameThenKind) });

  let definitions;
  try {
    definitions = loadStageDefinitions(root);
  } catch (e) {
    // ⚠️ THE PARSER'S OWN WORDS, NOT THE PATH IT WAS GIVEN: a SyntaxError names a position, and a
    // StageDefinitionError names the file relative to stages/.
    refusals.push(refusal(SYNC_REFUSAL.MALFORMED, e?.name === "SyntaxError" ? `a file under stages/ is not valid JSON (${e.message}).` : `stages/ ${e.message}`));
    return done();
  }
  if (definitions === null) {
    refusals.push(refusal(SYNC_REFUSAL.NO_DEFINITIONS, "no stage definitions exist under stages/, so there is nothing to generate from."));
    return done();
  }

  let skills;
  try {
    skills = generateStageSkills(definitions);
  } catch (e) {
    if (!(e instanceof StageSkillError)) throw e;
    refusals.push(refusal(SYNC_REFUSAL.MALFORMED, `stages/${e.message}`, null));
    return done();
  }

  let rootStat = null;
  try {
    rootStat = lstatSync(skillsRoot);
  } catch {
    /* reported below */
  }
  if (!rootStat || !rootStat.isDirectory()) {
    refusals.push(
      refusal(
        rootStat?.isSymbolicLink() ? SYNC_REFUSAL.LINKED_ENTRY : SYNC_REFUSAL.NO_SKILLS_DIR,
        rootStat?.isSymbolicLink() ? `${shown()}/ is a link; generated skills are not written through one.` : `${shown()}/ does not exist or is not a directory.`
      )
    );
    return done(skills);
  }

  const canonicalSkillsRoot = canonicalPath(skillsRoot);
  // ⚠️ THE DIRECTORY ITSELF MUST SIT WHERE IT APPEARS TO. A junction at pi-package/skills would put
  // every write somewhere else while every relative name still looked right.
  if (!isAtOrInside(canonicalSkillsRoot, canonicalPath(packageRoot)) || canonicalSkillsRoot !== canonicalPath(join(canonicalPath(packageRoot), SKILLS_DIR))) {
    refusals.push(refusal(SYNC_REFUSAL.PATH_ESCAPE, `${shown()}/ resolves outside ${PACKAGE_DIR}/.`));
    return done(skills);
  }

  /** Inside the skills directory, by canonical path, or a refusal. */
  const contained = (absolute, skill) => {
    const inside = isAtOrInside(canonicalPath(absolute), canonicalSkillsRoot) && canonicalPath(absolute) !== canonicalSkillsRoot;
    if (!inside) refusals.push(refusal(SYNC_REFUSAL.PATH_ESCAPE, `${shown(skill)} resolves outside ${shown()}/.`, skill));
    return inside;
  };

  const expected = new Set();
  for (const skill of skills) {
    expected.add(skill.name);
    const dir = join(skillsRoot, skill.name);
    const file = join(dir, SKILL_FILE);
    const relativeFile = shown(skill.name, SKILL_FILE);

    // ⚠️ THE ENTRY ITSELF FIRST, WITHOUT FOLLOWING IT. Resolving the path first would walk through a
    // link and report where it leads, when what needs saying is that a link is standing there.
    let dirStat = null;
    try {
      dirStat = lstatSync(dir);
    } catch {
      if (contained(file, skill.name)) drift.push({ kind: DRIFT.MISSING, skill: skill.name, path: relativeFile });
      continue;
    }
    if (dirStat.isSymbolicLink()) {
      refusals.push(refusal(SYNC_REFUSAL.LINKED_ENTRY, `${shown(skill.name)} is a link; a generated skill is not written through one.`, skill.name));
      continue;
    }
    if (!contained(file, skill.name)) continue;
    if (!dirStat.isDirectory()) {
      refusals.push(refusal(SYNC_REFUSAL.NOT_A_SKILL, `${shown(skill.name)} is not a directory, so it cannot be the generated skill of that name.`, skill.name));
      continue;
    }

    let entries;
    try {
      entries = readdirSync(dir).sort(byCodeUnit);
    } catch (e) {
      refusals.push(ioRefusal(e, shown(skill.name), skill.name));
      continue;
    }
    const unowned = entries.filter((entry) => entry !== SKILL_FILE);
    // ⚠️ A GENERATED SKILL HOLDS ITS SKILL.md AND NOTHING ELSE. A file beside it is not the generator's
    // to keep, replace or delete, and Pi would package it as part of the skill.
    if (unowned.length > 0) {
      refusals.push(refusal(SYNC_REFUSAL.UNOWNED_CONTENT, `${shown(skill.name)} holds files the generator does not own: ${unowned.join(", ")}.`, skill.name));
      continue;
    }
    if (!entries.includes(SKILL_FILE)) {
      drift.push({ kind: DRIFT.MISSING, skill: skill.name, path: relativeFile });
      continue;
    }

    let fileStat;
    try {
      fileStat = lstatSync(file);
    } catch (e) {
      refusals.push(ioRefusal(e, relativeFile, skill.name));
      continue;
    }
    if (fileStat.isSymbolicLink() || !fileStat.isFile()) {
      refusals.push(refusal(fileStat.isSymbolicLink() ? SYNC_REFUSAL.LINKED_ENTRY : SYNC_REFUSAL.NOT_A_SKILL, `${relativeFile} is not a regular file.`, skill.name));
      continue;
    }

    try {
      // ⚠️ BYTES, NOT TEXT. A line-ending or encoding difference is staleness, and a comparison that
      // normalised it would pass a file Pi reads differently on another platform.
      if (!readFileSync(file).equals(Buffer.from(skill.content, "utf8"))) drift.push({ kind: DRIFT.STALE, skill: skill.name, path: relativeFile });
    } catch (e) {
      refusals.push(ioRefusal(e, relativeFile, skill.name));
    }
  }

  let present;
  try {
    present = readdirSync(skillsRoot).sort(byCodeUnit);
  } catch (e) {
    refusals.push(ioRefusal(e, `${shown()}/`));
    return done(skills);
  }

  for (const name of present) {
    // ⚠️ THE OWNERSHIP BOUNDARY. `kiln-planning` and every other name the generator does not own stops
    // here, before it is so much as opened.
    if (!isStageSkillName(name) || expected.has(name)) continue;

    const dir = join(skillsRoot, name);
    const relativeFile = shown(name, SKILL_FILE);

    let stat;
    try {
      stat = lstatSync(dir);
    } catch (e) {
      refusals.push(ioRefusal(e, shown(name), name));
      continue;
    }
    if (stat.isSymbolicLink()) {
      refusals.push(refusal(SYNC_REFUSAL.LINKED_ENTRY, `${shown(name)} is a link; it is not followed, and not removed.`, name));
      continue;
    }
    if (!contained(dir, name)) continue;
    if (!stat.isDirectory()) {
      refusals.push(refusal(SYNC_REFUSAL.NOT_A_SKILL, `${shown(name)} is not a directory, so it is not a generated skill to remove.`, name));
      continue;
    }

    let entries;
    try {
      entries = readdirSync(dir).sort(byCodeUnit);
    } catch (e) {
      refusals.push(ioRefusal(e, shown(name), name));
      continue;
    }

    let owned = false;
    if (entries.length === 1 && entries[0] === SKILL_FILE) {
      try {
        const fileStat = lstatSync(join(dir, SKILL_FILE));
        if (fileStat.isFile() && !fileStat.isSymbolicLink()) {
          const text = readFileSync(join(dir, SKILL_FILE), "utf8");
          owned = text.startsWith(`---\nname: "${name}"\n`) && text.includes(`\n${GENERATED_HEADER}`);
        }
      } catch (e) {
        refusals.push(ioRefusal(e, relativeFile, name));
        continue;
      }
    }
    drift.push({ kind: DRIFT.ORPHANED, skill: name, path: shown(name), owned, unowned: owned ? [] : entries });
  }

  return done(skills);
}

/**
 * The check: the plan, reported, with nothing written.
 *
 * @returns {{status: "clean"|"drift"|"refused", drift: object[], refusals: object[], expected: number}}
 */
export function checkStageSkills(toolRoot) {
  const plan = planStageSkills(toolRoot);
  const status = plan.refusals.length > 0 ? "refused" : plan.drift.length > 0 ? "drift" : "clean";
  return { status, drift: plan.drift, refusals: plan.refusals, expected: plan.skills.length };
}

/**
 * The write: create what is missing, replace what is stale, remove what is orphaned and owned - or,
 * when anything in the plan is refused or an orphan is not the generator's, write nothing at all.
 *
 * @returns {Promise<{status: "written"|"refused", changes: object[], refusals: object[], expected: number}>}
 */
export async function writeStageSkills(toolRoot) {
  const plan = planStageSkills(toolRoot);
  const refusals = [...plan.refusals];

  for (const item of plan.drift)
    if (item.kind === DRIFT.ORPHANED && !item.owned)
      refusals.push(
        refusal(
          SYNC_REFUSAL.UNOWNED_CONTENT,
          `${item.path} is orphaned but holds content the generator did not write (${item.unowned.join(", ") || "no generated SKILL.md"}); it is not removed.`,
          item.skill
        )
      );

  if (refusals.length > 0) return { status: "refused", changes: [], refusals: refusals.sort(byNameThenKind), expected: plan.skills.length };

  const root = canonicalPath(toolRoot);
  const skillsRoot = join(root, PACKAGE_DIR, SKILLS_DIR);
  const bySkill = new Map(plan.skills.map((skill) => [skill.name, skill]));
  const changes = [];

  for (const item of plan.drift) {
    const dir = join(skillsRoot, item.skill);
    try {
      if (item.kind === DRIFT.ORPHANED) {
        // ⚠️ ONE FILE, THEN AN EMPTY DIRECTORY - NEVER A RECURSIVE REMOVAL. If anything appeared in
        // the directory since it was planned, `rmdir` fails and the stray file survives.
        unlinkSync(join(dir, SKILL_FILE));
        rmdirSync(dir);
      } else {
        if (!existsSync(dir)) mkdirSync(dir);
        await atomicWrite(join(dir, SKILL_FILE), bySkill.get(item.skill).content);
      }
      changes.push(item);
    } catch (e) {
      return {
        status: "refused",
        changes,
        refusals: [ioRefusal(e, item.path, item.skill)],
        expected: plan.skills.length,
      };
    }
  }

  // ⚠️ WRITTEN IS NOT THE CLAIM; AGREEING IS. The directory is planned again, and a write that did not
  // produce a clean plan is reported as unverified rather than as done.
  const after = checkStageSkills(toolRoot);
  if (after.status !== "clean")
    return {
      status: "refused",
      changes,
      refusals: [refusal(SYNC_REFUSAL.UNVERIFIED, `after writing, the skills directory still does not match the definitions (${after.status}).`)],
      expected: plan.skills.length,
    };

  return { status: "written", changes, refusals: [], expected: plan.skills.length };
}
